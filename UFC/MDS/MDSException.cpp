//------------------------------------------------------------------------------------------------------------------------
#include "MDSException.h"
//------------------------------------------------------------------------------------------------------------------------
namespace MDS
{
//------------------------------------------------------------------------------------------------------------------------
MDSException::MDSException( void )
: UFC::Exception( "" )
, FMessage( "" )
{
}
//------------------------------------------------------------------------------------------------------------------------
MDSException::~MDSException( void ) throw()
{
}
//------------------------------------------------------------------------------------------------------------------------
void MDSException::Throw( const char* FormatStr, ... )
{
	FMessage = "";

	if( FormatStr != NULL )
	{
		char Buffer[ 512 ];
		Buffer[0] = '\0';

		va_list va;
		va_start( va , FormatStr );
		int Count = vsnprintf( Buffer, 512, FormatStr, va );
		va_end( va );

		if( Count > 0 )
			FMessage = Buffer;
	}

	throw( *this );
}
//------------------------------------------------------------------------------------------------------------------------
const char* MDSException::what( void ) const throw()
{
	return FMessage.c_str();
}
//------------------------------------------------------------------------------------------------------------------------
} ///< namespace MDS
