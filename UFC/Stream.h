//-----------------------------------------------------------------------------------------------------------------
const int soFromBeginning = SEEK_SET;
const int soFromCurrent   = SEEK_CUR;
const int soFromEnd       = SEEK_END;
//-----------------------------------------------------------------------------------------------------------------
class PStream
{
protected:
      Int64 FPos;
public:
      PStream():FPos(0){}
      PStream( PStream& Src ):FPos( Src.FPos ){}
      virtual ~PStream(){};
      virtual int Read( void* Buffer, int Size ) = 0;
      virtual int Write( const void* Buffer, int Size ) = 0;
      virtual Int64 Seek( Int64 Offset, int Origin ) = 0;
      virtual const Int64 GetSize( void ) = 0;
      const Int64 GetPosition( void ){ return FPos; }
};
